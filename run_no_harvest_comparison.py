def build_model():
    """Build the TSA 24 ForestModel (no actions scheduled: no-harvest case)."""
    fm = ws3.forest.ForestModel(model_name='tsa24',
                                model_path='data/woodstock_model_files_tsa24',
                                base_year=BASE_YEAR,
                                horizon=HORIZON,
                                period_length=PERIOD_LENGTH,
                                max_age=MAX_AGE)
    fm.import_landscape_section()
    fm.import_areas_section()
    fm.import_yields_section()
    fm.import_actions_section()
    fm.import_transitions_section()
    fm.initialize_areas()
    fm.add_null_action()
    fm.reset_actions()
    fm.grow()
    return fm


def pct_diff(df_ws3, df_cbm, timestep='period', metrics=None):
    """Period-wise percent difference (libCBM as benchmark)."""
    if metrics is None:
        metrics = ['biomass_stock', 'dom_stock', 'eco_stock', 'net_emission']
    a = df_ws3.set_index(timestep)[metrics]
    b = df_cbm.set_index(timestep)[metrics]
    diff = (a - b).div(b).mul(100)
    return diff.reset_index()


def main(out_dir):
    fm = build_model()

    disturbance_type_mapping = [
        {'user_dist_type': 'harvest', 'default_dist_type': 'Clearcut harvesting without salvage'},
        {'user_dist_type': 'fire', 'default_dist_type': 'Wildfire'},
    ]
    for dtype_key in fm.dtypes:
        fm.dt(dtype_key).last_pass_disturbance = 'fire' if dtype_key[2] == dtype_key[4] else 'harvest'

    sit_config, sit_tables = fm.to_cbm_sit(softwood_volume_yname='swdvol',
                                           hardwood_volume_yname='hwdvol',
                                           admin_boundary='British Columbia',
                                           eco_boundary='Montane Cordillera',
                                           disturbance_type_mapping=disturbance_type_mapping)

    # libCBM: real landscape inventory, no-harvest dynamics over the model horizon
    cbm_output = run_cbm(sit_config, sit_tables, n_steps=fm.horizon * fm.period_length)

    # ws3: plug in the carbon yield curves and compile landscape carbon indicators
    c_curves_p = pd.read_pickle('curves/c_curves_p.pkl')
    c_curves_f = pd.read_pickle('curves/c_curves_f.pkl')
    plugin_c_curves(fm, c_curves_p, c_curves_f, sum_pools, sum_fluxes)

    os.makedirs(out_dir, exist_ok=True)

    df_cbm, df_ws3 = compare_ws3_libcbm(
        fm, cbm_output, disturbance_type_mapping, biomass_pools, dom_pools,
        total_emission, gross_growth, plots='whole',
        filename=os.path.join(out_dir, 'no_harvest_carbon_stock_whole_st.pdf'))
    df_cbm, df_ws3 = compare_ws3_libcbm(
        fm, cbm_output, disturbance_type_mapping, biomass_pools, dom_pools,
        total_emission, gross_growth, plots='individual',
        filename=os.path.join(out_dir, 'no_harvest_carbon_dynamics_individual_st.pdf'))

    df_diff = pct_diff(df_ws3, df_cbm)

    df_cbm.to_csv(os.path.join(out_dir, 'no_harvest_cbm.csv'), index=False)
    df_ws3.to_csv(os.path.join(out_dir, 'no_harvest_ws3.csv'), index=False)
    df_diff.to_csv(os.path.join(out_dir, 'no_harvest_pct_diff.csv'), index=False)
    df_diff.set_index('period').abs().mean().to_frame('mean_abs_pct_diff').to_csv(
        os.path.join(out_dir, 'no_harvest_pct_diff_summary.csv'))

    print(f'Wrote no-harvest comparison outputs to {out_dir}')


