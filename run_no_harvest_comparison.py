"""
No-harvest comparison: ws3 vs libCBM (TSA 24 case study).

Regenerates the artifacts in ``outputs/no_harvest/``:

  - ``no_harvest_cbm.csv``               libCBM: real landscape inventory, no harvest, model horizon
  - ``no_harvest_ws3.csv``               ws3: same landscape with carbon yield curves plugged in
  - ``no_harvest_pct_diff.csv``          period-wise percent difference (libCBM as benchmark)
  - ``no_harvest_pct_diff_summary.csv``  mean absolute percent difference per metric
  - ``no_harvest_carbon_stock_whole_st.pdf``
  - ``no_harvest_carbon_dynamics_individual_st.pdf``

Prerequisites
-------------
- ``ws3`` and ``libcbm`` installed (see ``requirements.txt``; both are pinned as submodules)
- carbon yield curves present in ``curves/`` (generated by ``generate_c_curves_tsa24.ipynb``)

Conventions
-----------
- This project's Woodstock-format model files use stand ages in *years* (5..475), so no
  ``convert_periods_to_years`` is needed. For Woodstock files that define time in periods,
  pass ``convert_periods_to_years=<period_length>`` to the ``import_*`` methods.
- ``ForestModel.inventory(period, ...)`` reports the inventory at the *end* of the period
  (aged by ``period_length``), matching Woodstock's period outputs (ws3 >= 1.0.5 parity).

Usage
-----
    python run_no_harvest_comparison.py [--out-dir outputs/no_harvest]
"""

